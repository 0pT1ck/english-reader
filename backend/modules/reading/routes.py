"""Endpoints for the reading loop.

Two surfaces, and they never touch. ``client_router`` is mounted under
``/v1/client`` and guarded by a device token; ``admin_router`` is mounted under
``/v1/admin`` and guarded by the admin credential. Architecture rule 4 says a
device token can never reach an admin capability — the admin surface can
re-ingest, delete and rewrite settings, and a credential able to do that has no
business travelling to a phone.

**This is the first client contract in the project.** Nothing existed under
``/v1/client`` before P2. Sideloaded clients update late, so rule 5 applies from
here on: fields may be added, never removed or given a new meaning.
"""

