class ClientEvent(BaseModel):
    """One reported interaction.

    ``idem_key`` is generated by the client, not the server: the client is the
    only party that knows whether this is the same event it failed to upload ten
    minutes ago on a train.
    """

    idem_key: str = Field(min_length=8, max_length=128, description="客户端生成的幂等键")
    type: str = Field(description="事件类型")
    payload: dict[str, Any] = Field(default_factory=dict)
    occurred_at: str | None = Field(default=None, description="客户端时钟，可能不准")


class EventBatch(BaseModel):
    events: list[ClientEvent] = Field(default_factory=list, max_length=500)


@client_router.get("/library", summary="文章清单")
async def library(
    device_id: DeviceId,
    shelf: str = Query("fresh", description="fresh 新备的 / archive 往期 / unread / read / all"),
    source: str | None = Query(None, description="generated / cet4 / cet6 / kaoyan"),
    sort: str | None = Query(None, description="按哪个指标排序，留空则用配置里的默认值"),
    desc: bool = Query(False, description="降序"),
) -> dict[str, Any]:
    """The library.

    There is no ``/today``: deciding what someone should read today needs the
    ability estimate and the selection logic, both of which are P3. The library
    is not a stopgap for that — the intended shape is "a few articles are
    prepared each day, you pick the ones you feel like", which is a list and a
    choice. ``/today`` will be *added* later, which rule 5 permits.
    """
    return service.library(
        auth.learner_for_device(device_id),
        shelf=shelf, source=source,
        # Omitting `sort` means "whatever the console is set to", so the default
        # ordering can be changed without touching a client.
        sort=sort or str(runtime_config.get("library_default_sort")),
        descending=desc,
    )


@client_router.get("/articles/{article_id}", summary="一篇文章的全部内容")
async def article(device_id: DeviceId, article_id: int) -> dict[str, Any]:
    """Text, sentences, every token's analysis, every gloss, and your marks.

    One response, then no further requests while reading. An article still being
    prepared comes back with a ``preparing`` block instead of an error — lazy
    ingest means asking for one is normal, not a mistake.
    """
    return service.article(auth.learner_for_device(device_id), article_id)


@client_router.post("/events", summary="批量上报交互事件")
async def report_events(device_id: DeviceId, batch: EventBatch) -> dict[str, Any]:
    """Accepts duplicates by design — a retry is the protocol working."""
    return service.ingest_events(
        device_id,
        auth.learner_for_device(device_id),
        [event.model_dump() for event in batch.events],
    )


