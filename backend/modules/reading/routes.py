@admin_router.get("/reading/calibration", summary="难度分能否排对三个等级")
async def admin_calibration() -> dict[str, Any]:
    """The acceptance test for the composite score, runnable at any time.

    A weighting that cannot order 四级 < 六级 ≈ 考研 is wrong, whatever it looks
    like — the three exam levels are the one sample in this project with a known
    answer. Exposed as an endpoint rather than a one-off script so that changing
    the weights in the console can be checked immediately.
    """
    # Every article that has been *analysed*, not only the ones that finished
    # annotation: the difficulty indicators come from the local analysis pass,
    # so a paper waiting on the model still has a usable score. Requiring
    # 'ready' here would mean the calibration could not be checked until an
    # entire corpus had been through the annotator.
    per_source = repository.scores_by_source()

    def median(values: list[float]) -> float | None:
        if not values:
            return None
        ordered = sorted(values)
        middle = len(ordered) // 2
        if len(ordered) % 2:
            return round(ordered[middle], 1)
        return round((ordered[middle - 1] + ordered[middle]) / 2, 1)

    medians = {source: median(values) for source, values in per_source.items()}
    four, six, ky = medians.get("cet4"), medians.get("cet6"), medians.get("kaoyan")
    ordered = None
    if four is not None and six is not None and ky is not None:
        ordered = four < six and four < ky

    return {
        "weights": difficulty.weights(),
        "counts": {source: len(values) for source, values in per_source.items()},
        "medians": medians,
        "ordered_correctly": ordered,
        "note": "四级应低于六级与考研；六级与考研实测接近，考研略高。排不对说明权重或指标有问题。",
    }


